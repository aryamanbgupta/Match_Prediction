#!/usr/bin/env python
"""I12 v1 gates for the women's match model (coinflip + ELO baselines only).

NOTE (2026-08-01): the original "no odds exist -> no market gate" premise was
wrong — women's Polymarket odds DO exist (266 T20 markets; 175 join to the w1
pool via `scripts/build_womens_polymarket_odds.py` ->
`data/womens_polymarket/betting_odds_womens_w1.json`). The market-LL
comparison is regenerated by `scripts/eval_womens_market.py` and summarised in
`docs/I12_WOMENS_TRACK_SCOPING.md` § "Market data (2026-08-01)"; verdict: the
market beats w1 on LL on every liquidity slice that matters, so passing the
gates below is NOT an edge claim.

The same gates applied to the w2 league corpus (`data/xgb_match_data_w2`)
FAIL: the ELO baseline beats both league arms on both splits.

Per arm (base / swap) and split (test / golden):
  - avg log loss vs coinflip ln2
  - accuracy (p>0.5 picks winner)
  - resolution: mean |p - 0.5|  (Hundred lesson: compression = failure mode)
Fair baseline: logistic regression on the single strongest prior feature
(top-6 batting ELO diff), fit on train+validation, scored on the same splits.
The v1 skill claim requires beating BOTH coinflip and the ELO baseline on
test AND golden.

Usage (from repo root, after training):
    uv run python scripts/eval_womens_v1.py [--data-dir data/xgb_match_data_w1]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression

LN2 = float(np.log(2.0))


def _metrics(p: np.ndarray, y: np.ndarray) -> dict:
    p = np.clip(p, 1e-9, 1 - 1e-9)
    return {
        "n": len(y),
        "ll": float(-np.mean(y * np.log(p) + (1 - y) * np.log(1 - p))),
        "acc": float(np.mean((p > 0.5) == (y == 1))),
        "resolution": float(np.mean(np.abs(p - 0.5))),
    }


def _load_preds(model_dir: Path, name: str) -> dict[str, float]:
    data = json.loads((model_dir / name).read_text())
    rows = data.get("predictions", data)
    out = {}
    for key, rec in rows.items():
        out[key] = rec["p_team1"] if isinstance(rec, dict) else rec
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", type=Path,
                    default=Path("data/xgb_match_data_w1"))
    ap.add_argument("--arms", nargs="+",
                    default=["models/xgb_match_w1_base",
                             "models/xgb_match_w1_swap"])
    args = ap.parse_args()

    frames = {s: pd.read_parquet(args.data_dir / f"{s}.parquet")
              for s in ("train", "validation", "test", "golden_test")
              if (args.data_dir / f"{s}.parquet").exists()}
    for split, df in frames.items():
        print(f"{split}: {len(df)} rows, "
              f"{df['match_date'].min()} .. {df['match_date'].max()}")

    elo_cols = [c for c in frames["train"].columns
                if "elo" in c.lower() and "diff" in c.lower()]
    elo_col = ("top6_batting_elo_diff"
               if "top6_batting_elo_diff" in elo_cols else elo_cols[0])
    print(f"\nELO baseline feature: {elo_col} (candidates: {elo_cols})")

    fit = pd.concat([frames["train"], frames["validation"]])
    lr = LogisticRegression(C=1e6)
    lr.fit(fit[[elo_col]].fillna(0.0), fit["team1_wins"].astype(int))

    print(f"\n{'arm':28s} {'split':12s} {'n':>5s} {'LL':>8s} {'acc':>7s} "
          f"{'res':>7s}   (coinflip LL {LN2:.4f})")
    for split in ("test", "golden_test"):
        df = frames[split]
        y = df["team1_wins"].astype(int).to_numpy()
        p_elo = lr.predict_proba(df[[elo_col]].fillna(0.0))[:, 1]
        m = _metrics(p_elo, y)
        print(f"{'elo-logistic-baseline':28s} {split:12s} {m['n']:>5d} "
              f"{m['ll']:>8.4f} {m['acc']:>7.3f} {m['resolution']:>7.3f}")
        key_col = "match_id"
        for arm in args.arms:
            arm_dir = Path(arm)
            fname = ("test_predictions.json" if split == "test"
                     else "golden_predictions.json")
            if not (arm_dir / fname).exists():
                print(f"{arm_dir.name:28s} {split:12s}   (no {fname})")
                continue
            preds = _load_preds(arm_dir, fname)
            keys = df[key_col].astype(str)
            mask = keys.isin(preds).to_numpy()
            p = np.array([preds[k] for k in keys[mask]])
            m = _metrics(p, y[mask])
            print(f"{arm_dir.name:28s} {split:12s} {m['n']:>5d} "
                  f"{m['ll']:>8.4f} {m['acc']:>7.3f} {m['resolution']:>7.3f}")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
